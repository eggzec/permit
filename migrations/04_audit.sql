COMMENT ON COLUMN audit."auditLogLicenses"."changes"    IS 'Nullable JSONB diff capturing license-specific mutation context (e.g. {"licenseStatusCode": {"from": "ACTIVE", "to": "REVOKED"}}). NULL for read or query actions where no mutation occurred.';

